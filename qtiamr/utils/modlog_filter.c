uint8_t g_module_mask = LOG_ALL_DISABLED;


/****************************************************************************
 * Private Functions
 ****************************************************************************/

/****************************************************************************
 * Public Functions
 ****************************************************************************/

int modulemask(int mask)
{
  uint8_t oldmask;

  oldmask       = g_module_mask;
  g_module_mask |= (uint8_t)mask;

  return oldmask;
}
int moduleunmask(int mask)
{
  uint8_t oldmask;

  oldmask       = g_module_mask;
  g_module_mask &= (uint8_t)mask;

  return oldmask;
}
